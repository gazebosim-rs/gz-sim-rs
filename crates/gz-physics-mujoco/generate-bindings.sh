# Regenerates bindings/sys.rs from the MuJoCo 3.11.0 headers with bindgen-cli 0.72.1:
#   cargo install --locked bindgen-cli@0.72.1
#   MUJOCO_INCLUDE=/path/to/include ./generate-bindings.sh
# The default include directory is the one gz-physics vendors for its MuJoCo plugin.
set -eu
include=${MUJOCO_INCLUDE:-/home/nkoenig/work/gazebo/rust/gz-physics/build/third_party/mujoco_vendor/install/include}
cd "$(dirname "$0")"
functions='mj_version|mju_setLogHandler|mj_makeSpec|mj_deleteSpec|mj_compile|mjs_getError'
functions="$functions|mjs_findBody|mjs_addBody|mjs_addGeom|mjs_addFreeJoint|mjs_addJoint"
functions="$functions|mj_makeData|mj_deleteData|mj_deleteModel|mj_forward|mj_step"
functions="$functions|mj_kinematics|mj_comPos|mj_comVel|mj_objectVelocity"
{
  printf '%s\n' '// Copyright (C) 2026 Open Source Robotics Foundation' \
    '// SPDX-License-Identifier: Apache-2.0' \
    '// Generated by generate-bindings.sh from the MuJoCo 3.11.0 headers. Do not edit.'
  bindgen "$include/mujoco/mujoco.h" \
    --dynamic-loading MujocoApi --dynamic-link-require-all \
    --allowlist-function "$functions" \
    --allowlist-var 'mjVERSION_HEADER' \
    --allowlist-type 'mjtObj|mjtJoint|mjtGeom|mjtIntegrator|mjtWarning|mjtLogLevel' \
    --no-derive-default --no-doc-comments --no-prepend-enum-name \
    --rust-target 1.85 --rust-edition 2024 \
    -- -I"$include" |
    # native.rs binds the symbols with a single checked lookup path instead of the
    # generated per-symbol loader, and owns the library handle.
    sed -e '/^impl MujocoApi {/,$d' -e 's/^    __library: /    pub library: /'
} > bindings/sys.rs
